function isoAt(date: Date, hours: number, minutes: number): string {
  const copy = new Date(date);
  copy.setHours(hours, minutes, 0, 0);
  return copy.toISOString();
}

function daysAgo(days: number, hours: number, minutes: number): string {
  const date = new Date();
  date.setDate(date.getDate() - days);
  return isoAt(date, hours, minutes);
}

function atDate(isoDate: string, hours: number, minutes: number): string {
  const date = new Date(`${isoDate}T00:00:00`);
  date.setHours(hours, minutes, 0, 0);
  return date.toISOString();
}

function nowIso() {
  return new Date().toISOString();
}

